const Glyph* find(char c) {
    for (const Glyph& g : kGlyphs)
        if (g.c == c) return &g;
    return nullptr;
}

struct Extent {
    int left, width;  // used columns
};

Extent extent_of(const Glyph& g) {
    int lo = kGlyphW, hi = -1;
    for (uint8_t r : g.rows) {
        for (int col = 0; col < kGlyphW; ++col) {
            if (r & (1 << (kGlyphW - 1 - col))) {
                lo = col < lo ? col : lo;
                hi = col > hi ? col : hi;
            }
        }
    }
    return hi < 0 ? Extent{0, 0} : Extent{lo, hi - lo + 1};
}

bool is_digit(char c) { return c >= '0' && c <= '9'; }

// Columns a character takes including the gap after it.
int advance_cols(char c) {
    if (c == ' ') return 4;
    if (is_digit(c)) return kGlyphW + 1;
    const Glyph* g = find(c);
    if (!g) return kGlyphW + 1;
    return extent_of(*g).width + 1;
}

