int text_width(const char* s, int scale) {
    int cols = 0;
    for (; *s; ++s) cols += advance_cols(*s);
    return cols > 0 ? (cols - 1) * scale : 0;
}

int text_height(int scale) { return kGlyphH * scale; }

void draw_text(Surface& sf, int x, int y, const char* s, int scale, uint16_t colour, const Rect* clip, bool rotate180) {
    const int w = text_width(s, scale), h = text_height(scale);
    int pen = 0;  // in columns
    for (; *s; ++s) {
        const Glyph* g = find(*s);
        if (g) {
            // Digits sit centred in a fixed cell; other glyphs start at their first used column.
            const Extent e = extent_of(*g);
            const int origin = is_digit(*s) ? 0 : e.left;
            for (int row = 0; row < kGlyphH; ++row) {
                for (int col = 0; col < kGlyphW; ++col) {
                    if (!(g->rows[row] & (1 << (kGlyphW - 1 - col)))) continue;
                    for (int dy = 0; dy < scale; ++dy) {
                        for (int dx = 0; dx < scale; ++dx) {
                            const int px = (pen + col - origin) * scale + dx;
                            const int py = row * scale + dy;
                            const int sx = rotate180 ? x + w - 1 - px : x + px;
                            const int sy = rotate180 ? y + h - 1 - py : y + py;
                            if (clip && (sx < clip->x0 || sx > clip->x1 || sy < clip->y0 || sy > clip->y1)) continue;
                            sf.set(sx, sy, colour);
                        }
                    }
                }
            }
        }
        pen += advance_cols(*s);
    }
}

size_t fold_text(const char* in, char* out, size_t cap) {
    if (cap == 0) return 0;
    // Base letters for U+00C0 to U+00FF; 0 means "no sensible equivalent".
    static const char kLatin1[] = "AAAAAAACEEEEIIIIDNOOOOO\0OUUUUY\0SAAAAAAACEEEEIIII\0NOOOOO\0OUUUUY\0Y";
    size_t n = 0;
    bool unknown = false;
    auto put = [&](char c) {
        if (n + 1 < cap) out[n++] = c;
    };
    auto flush_unknown = [&]() {
        if (unknown) put('?');
        unknown = false;
    };
    while (*in) {
        const unsigned char b = static_cast<unsigned char>(*in);
        if (b < 0x80) {
            char c = char(b);
            ++in;
            if (c >= 'a' && c <= 'z') c = char(c - 'a' + 'A');
            if (c == '\t' || c == '\n' || c == '\r') c = ' ';
            if (find(c) || c == ' ') {
                flush_unknown();
                put(c);
            } else {
                unknown = true;
            }
            continue;
        }
        // Decode one UTF-8 sequence.
        uint32_t cp = 0;
        int len = 1;
        if ((b & 0xE0) == 0xC0) cp = b & 0x1F, len = 2;
        else if ((b & 0xF0) == 0xE0) cp = b & 0x0F, len = 3;
        else if ((b & 0xF8) == 0xF0) cp = b & 0x07, len = 4;
        int taken = 1;
        for (; taken < len && (static_cast<unsigned char>(in[taken]) & 0xC0) == 0x80; ++taken) cp = (cp << 6) | (static_cast<unsigned char>(in[taken]) & 0x3F);
        in += taken;
        if (taken != len) {
            unknown = true;
            continue;
        }
        char repl = 0;
        if (cp >= 0xC0 && cp <= 0xFF) repl = kLatin1[cp - 0xC0];
        else if (cp == 0x2018 || cp == 0x2019 || cp == 0x2032) repl = '\'';
        else if (cp == 0x201C || cp == 0x201D) repl = '"';
        else if (cp == 0x2013 || cp == 0x2014 || cp == 0x2212) repl = '-';
        else if (cp == 0xA0) repl = ' ';
        if (cp == 0x2026) {
            flush_unknown();
            put('.'), put('.'), put('.');
        } else if (repl) {
            flush_unknown();
            put(repl);
        } else {
            unknown = true;
        }
    }
    flush_unknown();
    out[n] = '\0';
    return n;
}

